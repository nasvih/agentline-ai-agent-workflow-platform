/* English plural, kept as a helper only so both halves read the same way */
export const enN = (n, one, many) => `${n} ${Number(n) === 1 ? one : many}`;

/**
 * A label that lives inside a demo record rather than in the interface.
 * The record stores the English string — that string is the key — so the
 * store schema never changes and a workspace saved before this file
 * existed still opens. A value with no entry comes back untouched, which
 * is what keeps names, ids and technical tokens in Latin.
 */
export function dataLabel(t, group, value) {
  if (value === null || value === undefined || value === '') return value;
  const map = t(`data.${group}`);
  if (map && typeof map === 'object' && Object.prototype.hasOwnProperty.call(map, value)) return map[value];
  return value;
}

