/* ============================================================
   Agentline — the two dictionaries.

   `en` is the app exactly as it has always read. `ar` is the same app
   written in Arabic — written, not translated word for word, because a
   sentence that reads like a machine rendered it undoes the point of
   offering the language at all.

   Shape rules:
     - both halves carry the same keys; a missing `ar` key falls back to
       `en`, so a gap degrades to English rather than to a key path
     - a value is a string, an array, or a function of the interpolation
       variables when the sentence has to agree with a number
     - `{name}` style placeholders are filled by lib/i18n.js

   Arabic counted nouns take four shapes. `arN` below picks the right
   one, so "1 run", "2 runs" and "15 runs" come out as تشغيلة واحدة,
   تشغيلتان and ١٥ تشغيلة rather than one shape stretched over all three.
   ============================================================ */

/**
 * Arabic number agreement.
 * @param {number} n
 * @param {{one:string, two:string, few:string, many:string}} f
 *   one  — 1, the noun alone (تشغيلة واحدة)
 *   two  — 2, the dual (تشغيلتان)
 *   few  — 3-10, numeral + broken plural (٣ تشغيلات)
 *   many — 11+ and 0, numeral + singular accusative (١٥ تشغيلة)
 */
export function arN(n, f) {
  const i = Math.abs(Math.trunc(Number(n) || 0));
  const r = i % 100;
  if (i === 1) return f.one;
  if (i === 2) return f.two;
  if (r >= 3 && r <= 10) return `${i} ${f.few}`;
  return `${i} ${f.many}`;
}

